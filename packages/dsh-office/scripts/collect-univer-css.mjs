/**
 * Collects every @univerjs package's lib/index.css into a generated TS
 * module so the client bundle can inject them as one style tag (our loader
 * serves a single client.js artifact — no CSS file routing).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkgJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const names = Object.keys(pkgJson.dependencies ?? {}).filter((name) => name.startsWith('@univerjs/'))

let combined = ''
for (const name of names.sort()) {
  try {
    const cssPath = require.resolve(`${name}/lib/index.css`)
    combined += `\n/* ${name} */\n` + readFileSync(cssPath, 'utf8')
  } catch {
    // package without css -> skip
  }
}
const out = join(root, 'src', 'client', 'univer-css.gen.ts')
writeFileSync(out, `/** AUTO-GENERATED by scripts/collect-univer-css.mjs - do not edit. */\nexport const UNIVER_CSS = ${JSON.stringify(combined)}\n`)
console.log(`[collect-univer-css] ${combined.length} chars from ${names.length} packages -> src/client/univer-css.gen.ts`)
